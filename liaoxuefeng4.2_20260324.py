print('hello, world')  # 输出单个字符串'hello, world'
print('the quick brown fox','jumps over','the lazy dog')  # 输出多个字符串'the quick brown fox jumps over the lazy dog'
print(300)  # 输出数字'300'
print(100+200)  # 输出100+200的计算结果'300'
print('100 + 200 =',100+200)  # 输出算式100+200=300
name = input('please enter your name:')  # 输入并定义变量name
print('hello,',name)  # 变量name在输入名字后输出字符串'hello, 名字'
age = input('please enter your age:')  # 输入并定义变量age
print('hello,', name,', you are', age, 'years old')  # 变量age在输入年龄后连同前面输入的变量name输出字符串'hello, 名字, you are 年龄 years old'
print('练习')  # 输出单个字符串'练习'
print('1024 * 768 =',1024*768)  # 输出1024*768的计算结果'786432'